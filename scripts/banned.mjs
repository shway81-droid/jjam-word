/* ── 안전 기준 금칙어 (PRD 3절) ──
   교실 화면에 한 번 나가면 되돌릴 수 없는 말들이다. 사람 검토에만 맡기지 않고
   validate-data.mjs 가 CI 에서 강제한다.

   한국어에는 낱말 경계가 없어, 짧은 금칙어를 그대로 쓰면 멀쩡한 말을 잡는다.
   아래 예외는 전부 이 게이트를 돌리다 실제로 걸린 오탐이다 — 게이트가 늑대를
   잘못 부르면 사람이 게이트를 끄게 되므로, 오탐은 발견될 때마다 여기서 막고
   banned.test.mjs 에 사례를 남긴다.

     설거지 → '거지'          사장님·교장님 → '장님'
     계모임 → '계모'          불이 꺼져요 → '꺼져'
     영향을 미친 → '미친'      폭포가 장관이다 → '장관'(그래서 목록에서 뺐다)  */

export const BANNED = [
  {
    re: /병신|바보|멍청|(?<![을를에]\s)미친|죽어|짜증|꺼져\s*$|꺼져라|꺼지라/,
    why: '비속어·모욕 표현 금지',
  },
  {
    re: /벙어리|귀머거리|(?<![사부과교원실반])장님|절름발이|불구자|앉은뱅이|외눈/,
    why: '장애 비하 표현 금지 (속담 원문이라도 제외)',
  },
  { re: /뚱뚱|못생|살찐|대머리|난쟁이/, why: '외모 소재 금지' },
  { re: /가난|(?<!설)거지|부잣집|형편|이혼|계모(?!임)|의붓/, why: '가정 형편·가족 형태 소재 금지' },
  { re: /일등|꼴찌|등수|시험\s?점수|성적표/, why: '성적·등수 소재 금지' },
  { re: /하나님|부처님|예수|교회|성경|불경|기도문|천국/, why: '종교 소재 금지' },
  { re: /대통령|국회|정당|여당|야당|선거/, why: '정치 소재 금지' },
];

/** 걸린 금칙어의 사유들. 깨끗하면 빈 배열. */
export function violations(text) {
  return BANNED.filter((b) => b.re.test(text)).map((b) => b.why);
}
